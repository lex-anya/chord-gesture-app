// ── Camera ───────────────────────────────────────────────
async function startCamera() {
  const stream = await navigator.mediaDevices.getUserMedia({
    video: { width: 1280, height: 720, facingMode: "user" },
    audio: false,
  });
  video.srcObject = stream;

  // Wait for video to be ready
  await new Promise(resolve => video.onloadedmetadata = resolve);

  // Match canvas size to the actual rendered size of the container
  const rect = video.getBoundingClientRect();
  canvas.width  = rect.width;
  canvas.height = rect.height;
}

// ── Star field ────────────────────────────────────────────
const stars = Array.from({ length: 350 }, () => ({
  x:       Math.random() * window.innerWidth,
  y:       Math.random() * window.innerHeight,
  radius:  Math.random() * 1.0 + 0.3,
  opacity: Math.random() * 0.8 + 0.3,
  twinkle: Math.random() * 0.025 + 0.003,  // wider speed range
  phase:   Math.random() * Math.PI * 2,
  style:   Math.floor(Math.random() * 3),   // 0=sine, 1=random flicker, 2=steady
}));

function drawStars() {
  stars.forEach(star => {
    star.phase += star.twinkle;
    
    let op;
    if (star.style === 0) {
      // smooth sine twinkle
      op = star.opacity * (0.6 + 0.4 * Math.sin(star.phase));
    } else if (star.style === 1) {
      // occasional random flicker
      op = star.opacity * (Math.random() > 0.98 ? 0.2 : 1.0);
    } else {
      // mostly steady with very subtle drift
      op = star.opacity * (0.85 + 0.15 * Math.sin(star.phase * 0.3));
    }

    ctx.beginPath();
    ctx.arc(star.x, star.y, star.radius, 0, Math.PI * 2);
    ctx.fillStyle = `rgba(255, 255, 255, ${op})`;
    ctx.fill();
  });
}

// ── Particle trails ───────────────────────────────────────
const FINGERTIP_INDICES = [4, 8, 12, 16, 20]; // thumb, index, middle, ring, pinky

const trails = {
  Left:  Array.from({ length: 5 }, () => []),
  Right: Array.from({ length: 5 }, () => []),
};

function updateTrails(landmarks, handLabel) {
  if (!landmarks || landmarks.length < 21) return;
  const { renderWidth, renderHeight, offsetX, offsetY } = getVideoRenderRect();

  FINGERTIP_INDICES.forEach((tipIndex, i) => {
    const lm = landmarks[tipIndex];
    const x = offsetX + (1 - lm.x) * renderWidth;
    const y = offsetY + lm.y * renderHeight;

    // Only spawn particles if fingertip moved enough
    const trail = trails[handLabel][i];
    const last = trail[trail.length - 1];
    const moved = !last || Math.hypot(x - last.x, y - last.y) > 3;

    if (moved) {
      for (let j = 0; j < 2; j++) {
        trail.push({
          x: x + (Math.random() - 0.5) * 8,
          y: y + (Math.random() - 0.5) * 8,
          vx: (Math.random() - 0.5) * 1.2,
          vy: -Math.random() * 0.8,
          life: 1.0,
          size: Math.random() * 1.8 + 0.4,
        });
      }
    }

    if (trail.length > 40) {
      trails[handLabel][i] = trail.slice(-40);
    }
  });
}

function drawTrails(handLabel) {
  const color = "255, 255, 255";  // same for both hands

  trails[handLabel].forEach((trail, i) => {
    trail.forEach(p => {
      // Move particle
      p.x  += p.vx;
      p.y  += p.vy;
      p.life -= 0.04;   // fade out over ~25 frames

      if (p.life <= 0) return;

      ctx.beginPath();
      ctx.arc(p.x, p.y, p.size * p.life, 0, Math.PI * 2);
      ctx.fillStyle = `rgba(${color}, ${p.life * 0.9})`;
      ctx.fill();
    });

    // Remove dead particles
    trails[handLabel][i] = trail.filter(p => p.life > 0);
  });
}

// ── Hand skeleton ─────────────────────────────────────────
function getVideoRenderRect() {
  const videoAspect = video.videoWidth / video.videoHeight;
  const canvasAspect = canvas.width / canvas.height;

  let renderWidth, renderHeight, offsetX, offsetY;

  if (videoAspect > canvasAspect) {
    renderWidth  = canvas.width;
    renderHeight = canvas.width / videoAspect;
    offsetX      = 0;
    offsetY      = (canvas.height - renderHeight) / 2;
  } else {
    renderWidth  = canvas.height * videoAspect;
    renderHeight = canvas.height;
    offsetX      = (canvas.width - renderWidth) / 2;
    offsetY      = 0;
  }

  return { renderWidth, renderHeight, offsetX, offsetY };
}

// MediaPipe hand connections — pairs of landmark indices to draw lines between
const HAND_CONNECTIONS = [
  [0,1],[1,2],[2,3],[3,4],         // thumb
  [0,5],[5,6],[6,7],[7,8],         // index
  [0,9],[9,10],[10,11],[11,12],    // middle
  [0,13],[13,14],[14,15],[15,16],  // ring
  [0,17],[17,18],[18,19],[19,20],  // pinky
  [5,9],[9,13],[13,17],            // palm
];

function drawSkeleton(landmarks, handLabel) {
  if (!landmarks || landmarks.length < 21) return;
  const { renderWidth, renderHeight, offsetX, offsetY } = getVideoRenderRect();

  const toPixel = (lm) => ({
    x: offsetX + (1 - lm.x) * renderWidth,
    y: offsetY + lm.y * renderHeight,
  });

  // Right hand violet, left hand blue
  const connectionColor = handLabel === "Left"
    ? "rgba(109, 40, 217, 0.9)"    // deep purple
    : "rgba(29, 78, 216, 0.9)";    // deep blue

  const jointColor = handLabel === "Left"
    ? "rgba(192, 132, 252, 0.95)"    // soft luminous violet
    : "rgba(96, 165, 250, 0.95)";    // soft luminous blue

  // Draw connections
  ctx.lineWidth = 2;
  ctx.strokeStyle = connectionColor;

  for (const [a, b] of HAND_CONNECTIONS) {
    const pA = toPixel(landmarks[a]);
    const pB = toPixel(landmarks[b]);
    ctx.beginPath();
    ctx.moveTo(pA.x, pA.y);
    ctx.lineTo(pB.x, pB.y);
    ctx.stroke();
  }

  // Draw joints
  for (const lm of landmarks) {
    const p = toPixel(lm);
    ctx.beginPath();
    ctx.arc(p.x, p.y, 4, 0, Math.PI * 2);
    ctx.fillStyle = jointColor;
    ctx.fill();
  }
}

