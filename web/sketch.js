function updateInversionOptions(slotIndex) {
  const select = document.getElementById(`inv-${slotIndex}`);
  if (!select) return;
  select.innerHTML = "";

  const root = state.slots[slotIndex].root;
  const type = state.slots[slotIndex].chordType;

  if (!root) {
    const opt = document.createElement("option");
    opt.value = 0; opt.textContent = "";
    select.appendChild(opt);
    return;
  }

  const notes = getChordNoteNames(root, type);
  notes.forEach((note, idx) => {
    const opt = document.createElement("option");
    opt.value = idx;
    opt.textContent = note;
    if (idx === state.slots[slotIndex].inversion) opt.selected = true;
    select.appendChild(opt);
  });
}

// ── Music theory helpers ──────────────────────────────────
const SHARPS = ["C","C#","D","D#","E","F","F#","G","G#","A","A#","B"];
const FLATS  = ["C","Db","D","Eb","E","F","Gb","G","Ab","A","Bb","B"];

const CHORD_FORMULAS = {
  "maj":  [0,4,7],  "min":  [0,3,7],  "dim":  [0,3,6],
  "aug":  [0,4,8],  "maj7": [0,4,7,11], "7":  [0,4,7,10],
  "min7": [0,3,7,10], "dim7": [0,3,6,9],
  "sus2": [0,2,7],  "sus4": [0,5,7],  "add9": [0,4,7,14],
};

function getChordNoteNames(root, chordType) {
  const useFlats = root.includes("b") || root === "F";
  const noteList = useFlats ? FLATS : SHARPS;
  const rootIdx  = noteList.indexOf(root);
  if (rootIdx === -1) return [root];
  return (CHORD_FORMULAS[chordType] || [0,4,7])
    .map(i => noteList[(rootIdx + i) % 12]);
}

