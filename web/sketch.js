function setActiveSlot(index) {
  // Remove active class from all slots
  for (let i = 0; i < 10; i++) {
    const input = document.getElementById(`root-${i}`);
    const typeEl = document.getElementById(`type-${i}`);
    const invEl = document.getElementById(`inv-${i}`);
    if (input) input.classList.remove("active");
    if (typeEl) typeEl.classList.remove("active");
    if (invEl) invEl.classList.remove("active");
  }

  // Add active class to targeted slot
  if (index !== null && index >= 0 && index < 10) {
    const input = document.getElementById(`root-${index}`);
    const typeEl = document.getElementById(`type-${index}`);
    const invEl = document.getElementById(`inv-${index}`);
    if (input) input.classList.add("active");
    if (typeEl) typeEl.classList.add("active");
    if (invEl) invEl.classList.add("active");
  }
}

function onConfirm() {
  if (state.activeSlot === null) return;
//   if (state.activeSlot === state.playingSlot) return;
  const slot = state.slots[state.activeSlot];
  if (!slot || !slot.root) return;

  // Update playing slot
  state.playingSlot = state.activeSlot;

  // Update now playing display
  const chordDisplay = document.getElementById("chord-display");
  if (chordDisplay) {
    chordDisplay.textContent = slot.display || `${slot.root}${slot.chordType}`;
    chordDisplay.classList.add("playing");
  }

  // Highlight playing slot
  setPlayingSlot(state.playingSlot);

  playChord(slot);
  console.log("Playing:", slot.display, "inversion:", slot.inversion); 
}

