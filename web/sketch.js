// ── Render loop ───────────────────────────────────────────
async function loop() {
  // Feed current video frame to MediaPipe
  if (hands && video.readyState === 4) {
    await hands.send({ image: video });
  }

  // Clear canvas
  ctx.clearRect(0, 0, canvas.width, canvas.height);

  // Draw stars
  drawStars();

  // Draw hands if detected
  if (latestHandResults && latestHandResults.multiHandLandmarks) {
  for (let i = 0; i < latestHandResults.multiHandLandmarks.length; i++) {
    const landmarks = latestHandResults.multiHandLandmarks[i];
    const handLabel = latestHandResults.multiHandedness[i].label;
    drawSkeleton(landmarks, handLabel);
    updateTrails(landmarks, handLabel);
    drawTrails(handLabel);
  }

  // ── Gesture detection ──────────────────────────────────
  const gestures = detectGestures(latestHandResults);

  // Pre-dwell highlight — show which slot is being targeted
  if (gestures.rawRightGesture !== undefined) {
        setActiveSlot(gestures.rawRightGesture - 1);
    } else {
        setActiveSlot(null);
    }

    // Confirmed slot selection after dwell
    if (gestures.slotIndex !== undefined) {
        state.activeSlot = gestures.slotIndex;
    }

    // Confirm/play
    if (gestures.confirm && !prevConfirmGesture) {
        const now = Date.now();
        if (now - lastConfirmTime > CONFIRM_COOLDOWN_MS) {
            lastConfirmTime = now;
            onConfirm();
        }
    }
    prevConfirmGesture = !!gestures.confirm;

    // Stop
    if (gestures.stop) {
        onStop();
    }
  }

  requestAnimationFrame(loop);
}